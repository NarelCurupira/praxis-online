create or replace function public.notification_push_allowed_v0113(target_user uuid, target_type text)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare p public.notification_preferences%rowtype;
begin
  select * into p from public.notification_preferences where user_id = target_user;
  if not found then
    return target_type in ('assignment','transfer');
  end if;
  if not p.push_enabled then return false; end if;
  return case target_type
    when 'assignment' then p.push_assignments
    when 'transfer' then p.push_transfers
    when 'status' then p.push_status
    when 'deadline' then p.push_deadlines
    else false
  end;
end
$$;

create or replace function public.create_user_notification_v0113(
  target_user uuid,
  target_workspace uuid,
  target_type text,
  target_severity text,
  target_title text,
  target_body text,
  target_movement bigint,
  target_process_number text,
  target_actor uuid,
  request_push boolean default false,
  extra_payload jsonb default '{}'::jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare notification_id uuid;
declare target_workspace_name text;
begin
  if target_user is null or target_workspace is null then return null; end if;
  if target_actor is not null and target_user = target_actor then return null; end if;
  if not exists (
    select 1 from public.workspace_members wm
    where wm.workspace_id = target_workspace and wm.user_id = target_user and wm.active
  ) then return null; end if;

  select w.name into target_workspace_name from public.workspaces w where w.id = target_workspace;

  insert into public.user_notifications(
    recipient_user_id, workspace_id, workspace_name, notification_type, severity,
    title, body, movement_id, process_number, actor_user_id, push_requested, payload
  ) values(
    target_user, target_workspace, coalesce(target_workspace_name,'Procuradoria'),
    target_type, target_severity, target_title, target_body,
    target_movement, coalesce(target_process_number,''), target_actor,
    coalesce(request_push,false) and public.notification_push_allowed_v0113(target_user,target_type),
    coalesce(extra_payload,'{}'::jsonb)
  ) returning id into notification_id;

  return notification_id;
end
$$;

revoke execute on function public.notification_push_allowed_v0113(uuid,text) from public, anon, authenticated;
revoke execute on function public.create_user_notification_v0113(uuid,uuid,text,text,text,text,bigint,text,uuid,boolean,jsonb) from public, anon, authenticated;

create or replace function public.notify_movement_change_v0113()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare actor uuid;
declare process_number text;
declare process_label text;
begin
  actor := coalesce(auth.uid(), new.updated_by, new.created_by);
  select c.judicial_number into process_number from public.cases c where c.id = new.case_id;
  process_label := case when trim(coalesce(process_number,'')) <> '' then process_number else 'sem número informado' end;

  if tg_op = 'INSERT' then
    if new.assigned_to is not null then
      perform public.create_user_notification_v0113(
        new.assigned_to, new.workspace_id, 'assignment',
        case when new.priority = 'Urgente' then 'urgent' else 'info' end,
        'Novo processo atribuído',
        'O processo ' || process_label || ' foi atribuído a você.',
        new.id, process_number, actor, true,
        jsonb_build_object('priority',new.priority,'workflow_status',new.workflow_status)
      );
    end if;
    return new;
  end if;

  -- Transferência entre Procuradorias: um único evento específico para o novo responsável.
  if old.workspace_id is distinct from new.workspace_id then
    if new.assigned_to is not null then
      perform public.create_user_notification_v0113(
        new.assigned_to, new.workspace_id, 'transfer', 'warning',
        'Processo transferido para sua Procuradoria',
        'O processo ' || process_label || ' foi transferido e atribuído a você.',
        new.id, process_number, actor, true,
        jsonb_build_object('source_workspace_id',old.workspace_id,'target_workspace_id',new.workspace_id)
      );
    end if;
    return new;
  end if;

  if old.assigned_to is distinct from new.assigned_to and new.assigned_to is not null then
    perform public.create_user_notification_v0113(
      new.assigned_to, new.workspace_id, 'assignment',
      case when new.priority = 'Urgente' then 'urgent' else 'info' end,
      'Processo atribuído a você',
      'O processo ' || process_label || ' foi redistribuído para sua fila.',
      new.id, process_number, actor, true,
      jsonb_build_object('previous_assignee',old.assigned_to)
    );
  end if;

  if old.workflow_status is distinct from new.workflow_status and new.assigned_to is not null then
    perform public.create_user_notification_v0113(
      new.assigned_to, new.workspace_id, 'status', 'info',
      'Status processual atualizado',
      'O processo ' || process_label || ' passou de “' || coalesce(old.workflow_status,'') || '” para “' || coalesce(new.workflow_status,'') || '”.',
      new.id, process_number, actor, true,
      jsonb_build_object('old_status',old.workflow_status,'new_status',new.workflow_status)
    );
  end if;

  if old.deadline_at is distinct from new.deadline_at and new.assigned_to is not null then
    perform public.create_user_notification_v0113(
      new.assigned_to, new.workspace_id, 'deadline', 'warning',
      'Prazo processual atualizado',
      case when new.deadline_at is null
        then 'O prazo do processo ' || process_label || ' foi removido.'
        else 'O prazo do processo ' || process_label || ' foi alterado para ' || to_char(new.deadline_at,'DD/MM/YYYY') || '.'
      end,
      new.id, process_number, actor, true,
      jsonb_build_object('old_deadline',old.deadline_at,'new_deadline',new.deadline_at)
    );
  end if;

  return new;
exception when others then
  -- Central/Push são subsistemas auxiliares: falhas nunca podem abortar a operação processual.
  return new;
end
$$;

revoke execute on function public.notify_movement_change_v0113() from public, anon, authenticated;

drop trigger if exists movement_notifications_v0113 on public.movements;
create trigger movement_notifications_v0113
after insert or update of assigned_to, workspace_id, workflow_status, deadline_at
on public.movements
for each row execute function public.notify_movement_change_v0113();

