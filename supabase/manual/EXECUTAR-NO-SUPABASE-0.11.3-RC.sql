-- ============================================================
-- 2. CENTRAL DE INFORMAÇÕES
-- ============================================================

create table if not exists public.user_notifications (
  id uuid primary key default gen_random_uuid(),
  recipient_user_id uuid not null references auth.users(id) on delete cascade,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  workspace_name text not null default '',
  notification_type text not null check (notification_type in ('assignment','transfer','status','deadline','system')),
  severity text not null default 'info' check (severity in ('info','success','warning','urgent')),
