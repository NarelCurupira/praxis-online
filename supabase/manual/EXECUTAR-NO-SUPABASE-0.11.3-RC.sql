-- ============================================================
-- 1. PREFERÊNCIAS DE NOTIFICAÇÃO
-- ============================================================

create table if not exists public.notification_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  push_enabled boolean not null default true,
  push_assignments boolean not null default true,
  push_transfers boolean not null default true,
  push_status boolean not null default false,
  push_deadlines boolean not null default false,
  updated_at timestamptz not null default now()
);

