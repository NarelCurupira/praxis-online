create or replace function public.queue_notification_push_v0113()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare cfg public.push_runtime_v0113%rowtype;
declare queued_count integer := 0;
begin
  if not new.push_requested then return new; end if;

  insert into public.push_deliveries(notification_id, subscription_id)
  select new.id, s.id
  from public.push_subscriptions s
  where s.user_id = new.recipient_user_id and s.enabled
  on conflict(notification_id, subscription_id) do nothing;
  get diagnostics queued_count = row_count;

  if queued_count > 0 then
    select * into cfg from public.push_runtime_v0113 where singleton = true;
    if cfg.dispatch_url is not null and cfg.dispatch_token is not null then
      perform net.http_post(
        url := cfg.dispatch_url,
        headers := jsonb_build_object('Content-Type','application/json'),
        body := jsonb_build_object('dispatch_token',cfg.dispatch_token::text),
        timeout_milliseconds := 5000
      );
    end if;
  end if;

  return new;
exception when others then
  -- Falha de entrega Push nunca pode abortar a operação processual nem a Central.
  return new;
end
$$;

revoke execute on function public.queue_notification_push_v0113() from public, anon, authenticated;

drop trigger if exists user_notifications_push_queue_v0113 on public.user_notifications;
create trigger user_notifications_push_queue_v0113
after insert on public.user_notifications
for each row execute function public.queue_notification_push_v0113();

-- A Edge Function usa Service Role e recebe lotes atomizados via SKIP LOCKED.
create or replace function public.claim_push_deliveries_v0113(
  target_user uuid default null,
  batch_limit integer default 50
)
returns table(
  delivery_id bigint,
  subscription_id uuid,
  endpoint text,
  p256dh text,
  auth_secret text,
  notification_id uuid,
  recipient_user_id uuid,
  workspace_id uuid,
  movement_id bigint,
  notification_type text,
  severity text,
  title text,
  body text
)
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with candidates as (
    select d.id
    from public.push_deliveries d
    join public.user_notifications n on n.id = d.notification_id
    join public.push_subscriptions s on s.id = d.subscription_id and s.enabled
    where ((d.state = 'queued' and d.next_attempt_at <= now())
        or (d.state = 'processing' and d.claimed_at < now() - interval '10 minutes'))
      and (target_user is null or n.recipient_user_id = target_user)
    order by d.id
    for update of d skip locked
    limit greatest(1,least(coalesce(batch_limit,50),100))
  ), claimed as (
    update public.push_deliveries d
       set state = 'processing', claimed_at = now(), attempts = d.attempts + 1
      from candidates c
     where d.id = c.id
    returning d.id, d.notification_id, d.subscription_id
  )
  select
    c.id, s.id, s.endpoint, s.p256dh, s.auth_secret,
    n.id, n.recipient_user_id, n.workspace_id, n.movement_id,
    n.notification_type, n.severity, n.title, n.body
  from claimed c
  join public.user_notifications n on n.id = c.notification_id
  join public.push_subscriptions s on s.id = c.subscription_id;
end
$$;

create or replace function public.complete_push_delivery_v0113(
  target_delivery bigint,
  succeeded boolean,
  permanent_failure boolean default false,
  error_message text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare target_subscription uuid;
declare attempt_count integer;
begin
  select subscription_id, attempts into target_subscription, attempt_count
  from public.push_deliveries where id = target_delivery for update;
  if target_subscription is null then return; end if;

  if succeeded then
    update public.push_deliveries
       set state = 'sent', sent_at = now(), last_error = ''
     where id = target_delivery;
    update public.push_subscriptions
       set failure_count = 0, last_error = '', last_seen_at = now(), updated_at = now()
     where id = target_subscription;
  elsif permanent_failure then
    update public.push_deliveries
       set state = 'failed', last_error = left(coalesce(error_message,''),1000)
     where id = target_delivery;
    update public.push_subscriptions
       set enabled = false,
           failure_count = failure_count + 1,
           last_error = left(coalesce(error_message,''),1000),
           updated_at = now()
     where id = target_subscription;
  else
    update public.push_deliveries
       set state = case when coalesce(attempt_count,0) >= 5 then 'failed' else 'queued' end,
           next_attempt_at = now() + make_interval(mins => least(60, greatest(2, coalesce(attempt_count,1) * 5))),
           last_error = left(coalesce(error_message,''),1000)
     where id = target_delivery;
    update public.push_subscriptions
       set failure_count = failure_count + 1,
           last_error = left(coalesce(error_message,''),1000),
           updated_at = now()
     where id = target_subscription;
  end if;
end
$$;

