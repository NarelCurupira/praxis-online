create or replace function public.get_notification_preferences_v0113()
returns table(
  push_enabled boolean,
  push_assignments boolean,
  push_transfers boolean,
  push_status boolean,
  push_deadlines boolean
)
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.notification_preferences(user_id)
  values(auth.uid())
  on conflict(user_id) do nothing;

  return query
  select p.push_enabled, p.push_assignments, p.push_transfers, p.push_status, p.push_deadlines
  from public.notification_preferences p
  where p.user_id = auth.uid();
end
$$;

create or replace function public.save_notification_preferences_v0113(
  new_push_enabled boolean,
  new_push_assignments boolean,
  new_push_transfers boolean,
  new_push_status boolean,
  new_push_deadlines boolean
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Sessão inválida.'; end if;
  insert into public.notification_preferences(
    user_id, push_enabled, push_assignments, push_transfers, push_status, push_deadlines, updated_at
  ) values(
    auth.uid(), coalesce(new_push_enabled,true), coalesce(new_push_assignments,true),
    coalesce(new_push_transfers,true), coalesce(new_push_status,false),
    coalesce(new_push_deadlines,false), now()
  )
  on conflict(user_id) do update set
    push_enabled = excluded.push_enabled,
    push_assignments = excluded.push_assignments,
    push_transfers = excluded.push_transfers,
    push_status = excluded.push_status,
    push_deadlines = excluded.push_deadlines,
    updated_at = now();
end
$$;

create or replace function public.upsert_push_subscription_v0113(
  subscription_endpoint text,
  subscription_p256dh text,
  subscription_auth text,
  subscription_user_agent text default ''
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare subscription_id uuid;
begin
  if auth.uid() is null then raise exception 'Sessão inválida.'; end if;
  if length(trim(coalesce(subscription_endpoint,''))) < 20 then raise exception 'Assinatura Push inválida.'; end if;
  if trim(coalesce(subscription_p256dh,'')) = '' or trim(coalesce(subscription_auth,'')) = '' then
    raise exception 'Chaves da assinatura Push não informadas.';
  end if;

  insert into public.push_subscriptions(
    user_id, endpoint, p256dh, auth_secret, user_agent, enabled, failure_count, last_error, last_seen_at, updated_at
  ) values(
    auth.uid(), subscription_endpoint, subscription_p256dh, subscription_auth,
    left(coalesce(subscription_user_agent,''), 500), true, 0, '', now(), now()
  )
  on conflict(endpoint) do update set
    user_id = auth.uid(),
    p256dh = excluded.p256dh,
    auth_secret = excluded.auth_secret,
    user_agent = excluded.user_agent,
    enabled = true,
    failure_count = 0,
    last_error = '',
    last_seen_at = now(),
    updated_at = now()
  returning id into subscription_id;

  return subscription_id;
end
$$;

